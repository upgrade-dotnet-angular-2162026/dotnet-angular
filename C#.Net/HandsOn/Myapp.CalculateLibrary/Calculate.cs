namespace Myapp.CalculateLibrary
{
    public class Calculate
    {
        public int Add(int a,int b)
        {
            return a + b;
        }
        public int Mul(int a,int b)
        {
            return a * b;
        }
        public int Sub(int a,int b)
        {
            return a - b;
        }
        public int Square(int k)
        {
            return k * k;
        }
    }
}
